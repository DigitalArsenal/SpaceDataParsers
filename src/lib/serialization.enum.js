export var SerializationFormat;
(function (SerializationFormat) {
    SerializationFormat[SerializationFormat["csv"] = 0] = "csv";
    SerializationFormat[SerializationFormat["json"] = 2] = "json";
    SerializationFormat[SerializationFormat["txt"] = 3] = "txt";
    SerializationFormat[SerializationFormat["kvn"] = 4] = "kvn";
    SerializationFormat[SerializationFormat["xml"] = 5] = "xml";
})(SerializationFormat || (SerializationFormat = {}));
